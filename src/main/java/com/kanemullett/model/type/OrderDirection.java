package com.kanemullett.model.type;

/**
 * Enumeration of sort directions used in {@link com.kanemullett.model.OrderBy}
 * objects to define the ordering of query results.
 */
public enum OrderDirection {

    /** Sorts results in ascending order (smallest to largest). */
    ASCENDING,

    /** Sorts results in descending order (largest to smallest). */
    DESCENDING
}
